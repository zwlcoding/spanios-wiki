export function inferCatalogCategorySlug(
  entry: RareDiseaseCatalogEntry,
): DiseaseCategorySlug {
  const explicitCategory = explicitCategoryBySlug[entry.slug];

  if (explicitCategory) {
    return explicitCategory;
  }

  const text =
    `${entry.nameZh} ${entry.nameEn} ${entry.slug}`.toLocaleLowerCase();
  const matchedRule = rules.find((rule) =>
    rule.keywords.some((keyword) => text.includes(keyword)),
  );

  return matchedRule?.categorySlug ?? 'multisystem';
}
